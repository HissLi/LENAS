#!/usr/bin/env python
"""Generate RTDosePrediction/<model>/CONFIG.md for an OpenKBP run.

Reads the genotype from `<model>/geno.py` and, when available, the final
validation/test scores from the experiment output directory.

Usage:
    python write_config_md.py --model NAS_37 --params 13195493 \
        --output-dir Experiment/RTDosePrediction/Output/NAS_37
"""

import argparse
import os
import re

REPO = "/home/zihanli/project/LENAS"
PY = "/home/zihanli/anaconda3/envs/lenas/bin/python"


def read_text(path):
    try:
        return open(path).read()
    except OSError:
        return ""


def parse_scores(out_dir):
    """Return dict with dose/dvh test scores and best validation index."""
    info = {}
    test_log = read_text(os.path.join(out_dir, "test_stdout.log"))
    m = re.search(r"Dose score is:\s*([0-9.]+)", test_log)
    if m:
        info["dose"] = float(m.group(1))
    m = re.search(r"DVH score is:\s*([0-9.]+)", test_log)
    if m:
        info["dvh"] = float(m.group(1))

    train_log = read_text(os.path.join(out_dir, "log.txt"))
    vals = re.findall(r"Average val evaluation index is\s+(-?[0-9.]+),\s+best is\s+(-?[0-9.]+)",
                      train_log)
    if vals:
        info["last_val"] = float(vals[-1][0])
        info["best_val"] = float(vals[-1][1])
    epochs = re.findall(r"^Epoch:\s*(\d+),\s*iter:\s*(\d+)", train_log, re.M)
    if epochs:
        info["last_epoch"] = int(epochs[-1][0])
        info["last_iter"] = int(epochs[-1][1])
    return info


def read_time(path):
    txt = read_text(path).strip()
    return txt or "—"


def genotype_text(model_dir):
    src = read_text(os.path.join(model_dir, "geno.py"))
    m = re.search(r'a = \("(.+?)", 1\)', src, re.S)
    if not m:
        return "—"
    g = m.group(1)
    # Wrap the long argument list for readability.
    g = g.replace("down=[", "down=[\n        ").replace("], up=[", "],\n    up=[")
    return g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--params", required=True, type=int)
    ap.add_argument("--output-dir", required=True)
    args = ap.parse_args()

    model = args.model
    out_dir = os.path.abspath(args.output_dir)
    model_dir = os.path.join(REPO, "RTDosePrediction", model)
    info = parse_scores(out_dir)

    started = read_time(os.path.join(out_dir, "train_start.txt"))
    finished = read_time(os.path.join(out_dir, "train_end.txt"))
    status = "finished" if info.get("dose") is not None else "training / incomplete"
    if info.get("dose") is not None:
        dose_row = f"{info['dose']:.6f}"
    else:
        dose_row = "—"
    if info.get("dvh") is not None:
        dvh_row = f"{info['dvh']:.6f}"
    else:
        dvh_row = "—"
    best_val = f"{info['best_val']:.6f} (negative mean dose MAE)" \
        if "best_val" in info else "—"

    L = []
    L.append(f"# {model} — dataset split, configuration, and results\n")
    L.append("OpenKBP single-model run using the same data pipeline, loss, optimizer and "
             "validation protocol as `NAS_29` and `Unet`.\n")
    L.append(f"All paths below are relative to `{REPO}`.\n")
    L.append("---\n")

    L.append("## 0. Run snapshot\n")
    L.append("| Item | Value |")
    L.append("|---|---|")
    L.append(f"| Status | **{status}** |")
    L.append(f"| Training started | {started} |")
    L.append(f"| Training finished | {finished} |")
    L.append(f"| Output directory | `{out_dir}` |")
    L.append(f"| Model | `SearchedNet` (U-NAS searched architecture {model}) |")
    L.append(f"| Parameters | **{args.params:,}** |")
    L.append(f"| GPU | NVIDIA RTX PRO 5000 72GB, GPU 0 |")
    L.append(f"| Best validation index | {best_val} |")
    L.append(f"| **Test dose score** | **{dose_row}** |")
    L.append(f"| **Test DVH score** | **{dvh_row}** |")
    L.append("")
    L.append("The final `result.md` and `Evaluation/` + `DVH/` artifacts are generated by "
             "`Output/dvh_analysis_model.py`, `Output/make_result_md_model.py`, "
             "`Output/ci_hi_analysis.py`, `Output/per_patient_table.py` and "
             "`Output/dvh_single_axes.py`.\n")
    L.append("---\n")

    L.append("## 1. Dataset split\n")
    L.append("Official OpenKBP partition, enforced by patient-ID ranges:\n")
    L.append("| Split | Patients | Count | Role |")
    L.append("|---|---|---:|---|")
    L.append("| Train | `pt_1` … `pt_200` | 200 | optimization |")
    L.append("| Validation | `pt_201` … `pt_240` | 40 | checkpoint selection |")
    L.append("| Test | `pt_241` … `pt_340` | 100 | final evaluation only |")
    L.append("")
    L.append("The split is defined in "
             "`DataLoader/dataloader_OpenKBP_C3D.py:122-124` (train/val), "
             f"`{model}/online_evaluation.py:8` (validation), and "
             f"`{model}/test.py:184` (test).\n")
    L.append("---\n")

    L.append("## 2. Input data and preprocessing\n")
    L.append("Identical for all models; implemented in "
             "`DataLoader/dataloader_OpenKBP_C3D.py`.\n")
    L.append("| Item | Value |")
    L.append("|---|---|")
    L.append("| Files read | `CT`, `dose`, `possible_dose_mask`, `PTV70/63/56`, 7 OARs |")
    L.append("| Input channels | **9** = PTV composite + 7 OAR masks + CT |")
    L.append("| PTV composite | `70/70·PTV70 + 63/70·PTV63 + 56/70·PTV56` |")
    L.append("| CT normalization | clip to `[-1024, 1500]`, divide by 1000 |")
    L.append("| Dose target | `dose / 70` |")
    L.append("| Loss mask | `possible_dose_mask` |")
    L.append("| Training augmentation | flips p=0.8 (axes 0,2), z-rotation p=0.3, "
             "translation p=0.8, max shift 20 |")
    L.append("| Validation transform | tensor conversion only |")
    L.append("| Dataset / DataLoader | 1000 samples/epoch, batch 2, shuffle, 4 workers |")
    L.append("")
    L.append("---\n")

    L.append("## 3. Model configuration\n")
    L.append(f"Genotype (`{model}/geno.py:4`):\n")
    L.append("```text")
    L.append(genotype_text(model_dir))
    L.append("```\n")
    L.append(f"Construction (`{model}/train.py:41-47`, identical in `test.py`):\n")
    L.append("```python")
    L.append("SearchedNet(in_channels=9, init_n_kernels=16, out_channels=1,")
    L.append("            depth=4, n_nodes=4, channel_change=True, gene=gene)")
    L.append("```\n")
    L.append(f"Parameters: **{args.params:,}**  \n")
    L.append("Input/output: `9×128×128×128` → `1×128×128×128` (normalized dose, ×70 Gy at "
             "inference).\n")
    L.append("---\n")

    L.append("## 4. Training configuration\n")
    L.append("| Setting | Value |")
    L.append("|---|---|")
    L.append("| Batch size | 2 (validation batch 1) |")
    L.append("| Iterations | **80,000** (`max_iter`) |")
    L.append("| Iterations / epoch | 500 (`batch_size × 500` samples) |")
    L.append("| Epochs | 160 |")
    L.append("| Optimizer | Adam, one parameter group |")
    L.append("| Learning rate | 3e-4, cosine decay to 1e-7 over 80,000 iterations |")
    L.append("| Weight decay | 3e-5 effective (the single-group Adam branch hard-codes it) |")
    L.append("| Betas / eps / AMSGrad | (0.9, 0.999) / 1e-8 / True |")
    L.append("| Loss | masked L1 (`nn.L1Loss`, mean) on `dose / 70`, "
             "`possible_dose_mask > 0` |")
    L.append("| Validation | dose MAE on patients 201–240, saved as negative mean |")
    L.append("| Checkpoint selection | best validation index |")
    L.append("| Random seed | none (runs are non-deterministic) |")
    L.append("")
    L.append("---\n")

    L.append("## 5. Test / evaluation configuration\n")
    L.append("| Setting | Value |")
    L.append("|---|---|")
    L.append("| Test patients | **241–340** |")
    L.append("| Checkpoint | `best_val_evaluation_index.pkl` |")
    L.append("| TTA | enabled: `[[], ['Z'], ['W'], ['Z','W']]` (4 predictions averaged) |")
    L.append("| Post-processing | zero outside `possible_dose_mask`, zero negatives, ×70 |")
    L.append("| Prediction output | `Output/" + model + "/Prediction/<pt>/dose.nii.gz` |")
    L.append("| Dose score | MAE over `possible_dose_mask > 0` (Gy) |")
    L.append("| DVH score | mean absolute difference over D1/D95/D99 (PTVs) and "
             "D_0.1cc/mean (OARs) |")
    L.append("")
    L.append("---\n")

    L.append("## 6. Commands used\n")
    L.append("```bash")
    L.append("cd " + os.path.join(REPO, "RTDosePrediction", model))
    L.append(PY + " geno.py                       # writes best_genotype.pkl")
    L.append(PY + " train.py --batch_size 2 --list_GPU_ids 0 --max_iter 80000")
    L.append(PY + " test.py --GPU_id 0 --TTA True")
    L.append("```\n")
    L.append("The full train → test → evaluation → DVH → `result.md` pipeline is "
             "`Output/run_nas_model_pipeline.sh " + model + "`.\n")
    L.append("---\n")

    L.append("## 7. Reproducibility notes\n")
    L.append("1. No random seed is set, so retraining the same genotype gives a slightly "
             "different score.")
    L.append("2. The prepared data directory is flat and contains all 340 patients; the "
             "split is enforced only by the patient-ID ranges above.")
    L.append("3. Effective weight decay is 3e-5, not the 1e-4 passed by `train.py`.")
    L.append("4. `wandb` runs offline (`WANDB_MODE=offline`).")
    L.append("5. Checkpoints (`*.pkl`, ~100–170 MB each) are git-ignored; only predictions, "
             "metrics, figures and reports are committed.")

    cfg_path = os.path.join(model_dir, "CONFIG.md")
    with open(cfg_path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {cfg_path}")


if __name__ == "__main__":
    main()
